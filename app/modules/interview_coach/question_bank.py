"""Loading, validating and indexing the bundled interview question bank.

The bank lives in ``data/sample/sample_interview_questions.json`` because it is
demo content: every question, every company and every scenario in it is
fictional. It is committed, so a fresh clone can run an interview immediately,
and it is regenerated by ``scripts/generate_interview_sample_data.py``.

Two things happen here that a plain ``json.load`` would not do:

* **The bank is validated as a contract, not just as JSON.** Pydantic checks the
  shape; :func:`_check_bank_contract` then checks the things that make a rubric
  usable - that identifiers are unique, that every question can be scored on
  technical accuracy *and* on business understanding, that a question offered in
  architecture mode actually carries architecture concepts, and that every
  follow-up which claims to target a concept targets one that exists. A bank
  that fails any of these is rejected at load time rather than producing a
  question that silently cannot be marked on half its dimensions.
* **Every question gets a rubric fingerprint.** A score is a verdict about a
  rubric, so each stored answer records the fingerprint of the rubric it was
  marked against. When the bank is retuned the old scores are kept and flagged
  rather than quietly averaging into a dashboard alongside scores that were
  earned under different rules.
"""

